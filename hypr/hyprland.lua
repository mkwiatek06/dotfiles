local saved_workspace = 10

local function save_workspace()
    saved_workspace = hl.get_active_workspace().id
    hl.dispatch(hl.dsp.exec_cmd("qs ipc call workspaces blink " .. saved_workspace))
end

local function go_to_saved_workspace()
    if hl.get_active_workspace().id ~= saved_workspace then
        hl.dispatch(hl.dsp.focus({ workspace = saved_workspace}))
    else
        hl.dispatch(hl.dsp.focus({ workspace = "previous" }))
    end
        
end

local function drag_to_saved_workspace()
    hl.dispatch(hl.dsp.window.move({ workspace = saved_workspace}))
end


local held = false
local done = false
local sequence = 0

local function hybrid_bind_a(time, fn_long)
    sequence = (sequence + 1) % 10
    local me_in_seq = sequence
    held = true

    hl.timer(function()
        if held == true then
            if sequence == me_in_seq then
                done = true
                fn_long()
            end
        end
    end, {
        timeout = time,
        type = "oneshot"
    })
end

local function hybrid_bind_r(fn_short)
    held = false

    if done == false then
        fn_short()
    end

    done = false
end


hl.bind(mainMod .. " + code:49",             function() hybrid_bind_a(500, save_workspace) end)
hl.bind(mainMod .. " + code:49",             function() hybrid_bind_r(go_to_saved_workspace) end, { release = true })
hl.bind(mainMod .. " + SHIFT + code:49",     drag_to_saved_workspace)

